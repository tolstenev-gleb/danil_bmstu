#include <stdio.h>

// 0 1 2 3  4  5
// 1 2 4 8 16 32

// Определить поведение печати пробелов
// 0: "2"
// 1: " 4"
// 2: "  8"
// 3: "   16"
// 4: "    32"


int main() {
  int n = 5, k = 1;
  printf("Enter n: ");
  scanf("%d", &n);
  for (int i = 0; i < n; i++) {
    printf("%d:", i);
    // Печать пробелов
    for (int j = 0; j < i; j++) {
      printf("    ");
    }
    // Вычисление текущей степени двойки
    k = k * 2;
    // Печать степени двойки
    printf("%d\n", k);
  }
  return 0;
}
